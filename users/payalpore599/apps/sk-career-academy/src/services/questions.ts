// Question generators for all subjects

function rand(a: number, b: number): number {
  return Math.floor(Math.random() * (b - a + 1)) + a;
}

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function shuffle<T>(a: T[]): T[] {
  const b = [...a];
  for (let i = b.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [b[i], b[j]] = [b[j], b[i]];
  }
  return b;
}

function makeOpts(correct: number): { options: string[]; answer: number } {
  const c = Number(correct);
  const range = Math.max(Math.abs(c) * 0.3, 5);
  const wrong: number[] = [];
  while (wrong.length < 3) {
    const v = c + rand(-Math.ceil(range), Math.ceil(range));
    if (v !== c && v > 0 && !wrong.includes(v)) wrong.push(v);
  }
  const opts = shuffle([String(c), ...wrong.map(String)]);
  return { options: opts, answer: opts.indexOf(String(c)) };
}

